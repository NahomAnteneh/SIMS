-- +goose Up
-- S1.1 Roles: Set default privileges so future tables follow least privilege:
-- collector_rw gets DML only (SELECT, INSERT, UPDATE, DELETE)
-- query_ro gets SELECT only

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO collector_rw;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT ON TABLES TO query_ro;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO collector_rw;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT ON SEQUENCES TO query_ro;

-- +goose Down
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLES FROM collector_rw;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE SELECT ON TABLES FROM query_ro;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE USAGE, SELECT ON SEQUENCES FROM collector_rw;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE SELECT ON SEQUENCES FROM query_ro;
